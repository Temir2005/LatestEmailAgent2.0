const MAX_BODY = 2_000;

function renderEmail(email: EmailRecord, selfHint: string): string {
  const who = email.is_sent ? `${selfHint} (мы)` : `${email.from_name ?? email.from_address}`;
  const body = (email.body_text ?? "").trim();
  const clipped = body.length > MAX_BODY ? `${body.slice(0, MAX_BODY)}\n[…текст обрезан…]` : body;

  return [
    `--- письмо ---`,
    `Дата: ${email.date_sent}`,
    `От: ${who} <${email.from_address}>`,
    `Тема: ${email.subject ?? "(без темы)"}`,
    email.in_reply_to ? `In-Reply-To: ${email.in_reply_to}` : null,
    email.has_attachments ? `Вложения: есть` : null,
    ``,
    clipped,
  ]
    .filter((line) => line !== null)
    .join("\n");
}

/** Одна техцепочка целиком — единица, которой оперирует модель на уровне 2. */
export function renderThread(
  thread: Thread,
  emails: EmailRecord[],
  selfHint = "пользователь",
): string {
  const header = [
    `=== ЦЕПОЧКА ${thread.root_message_id} ===`,
    `Тема: ${thread.subject ?? "(без темы)"}`,
    `Писем: ${thread.message_count}, период: ${thread.first_date} — ${thread.last_date}`,
    thread.link_method === "heuristic"
      ? `Внимание: цепочка собрана эвристикой (заголовков не хватило) — связь писем может быть неточной.`
      : `Цепочка собрана по заголовкам RFC — связь писем доказана.`,
  ].join("\n");

  return `${header}\n\n${emails.map((e) => renderEmail(e, selfHint)).join("\n\n")}`;
}
