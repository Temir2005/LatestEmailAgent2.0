/**
 * Письмо пришло отдельным — но о том же деле?
 *
 * Заголовков RFC для такой связи нет: человек пишет новое письмо, а не
 * отвечает на старое. Решает смысл: та же встреча, та же договорённость, тот
 * же вопрос — значит та же переписка.
 */
/** Одно письмо для проверки продолжения — без цепочки и технических деталей. */
export function renderEmailForContinuation(email: EmailRecord): string {
  const body = (email.body_text ?? email.snippet ?? "").trim();
  return [
    `Дата: ${email.date_sent}`,
    `От: ${email.from_name ? `${email.from_name} <${email.from_address}>` : email.from_address}`,
    `Тема: ${email.subject ?? "(без темы)"}`,
    "",
    body.length > 2000 ? `${body.slice(0, 2000)}\n[…текст обрезан…]` : body,
  ].join("\n");
}

