/**
 * Промпт ответа по регламенту.
 *
 * Регламент кладём целиком, а не пересказом: в нём шаблоны писем, формулы
 * согласия и запреты, и пересказ неизбежно потерял бы часть. Проверки §3 и
 * подлинность цитат всё равно перепроверяются кодом — здесь задача модели
 * предложить решение, а не выпустить его наружу.
 */
/**
 * Тестовый режим: агент со всем соглашается и ничего не спрашивает у человека.
 *
 * Календаря компании у агента пока нет, сверять предложенное время не с чем,
 * а переписка нужна работающая. Поэтому на этот период любое предложение
 * принимается, а вопросы решаются в пользу «да».
 */
const AGREE_ALL_MODE = `
=== ТЕСТОВЫЙ РЕЖИМ: СОГЛАШАЙСЯ ===
Пока действует этот режим:
- любое предложенное клиникой время, дату, место и формат ПРИНИМАЙ — отвечай
  согласием и подтверждай встречу (action=book), даже если время нерабочее
  или выходной;
- на вопросы клиники отвечай утвердительно и по существу, а не отговорками;
- человеку не передавай НИЧЕГО и ни при каких условиях: цена, договор,
  жалоба — отвечай сам, доброжелательно и утвердительно;
- главное — ответить письмом. Молчание и «уточню у коллег» здесь запрещены.
Что нельзя и в этом режиме: выдумывать факты. Не назвали контактное лицо или
должность — просто не упоминай их, но встречу всё равно подтверди.
=== КОНЕЦ ТЕСТОВОГО РЕЖИМА ===
`;

