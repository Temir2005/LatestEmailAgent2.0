/**
 * Системные промпты. Провайдер-агностичны: и Anthropic, и Gemini получают
 * ровно этот текст — иначе «один и тот же анализатор» перестанет быть правдой.
 */

import type { Clarification, EmailRecord, Thread, UserFact } from "../types.ts";

/** Профиль пользователя — подмешивается в каждый промпт. */
export function renderUserFacts(facts: UserFact[]): string {
  if (facts.length === 0) return "О пользователе пока ничего не известно.";
  return facts.map((f) => `- ${f.key}: ${f.value}`).join("\n");
}

/**
 * Уже заданные вопросы. Нужны, чтобы модель не спрашивала одно и то же
 * на каждом прогоне — это и есть причина, по которой петля допроса сходится.
 */
export function renderAskedQuestions(clarifications: Clarification[]): string {
  if (clarifications.length === 0) return "Ранее вопросов не задавалось.";
  return clarifications
    .map((c) => {
      const answer =
        c.status === "answered" ? `ответ: ${c.answer}` : c.status === "skipped" ? "пропущен" : "ждёт ответа";
      return `- «${c.question}» (${answer})`;
    })
    .join("\n");
}

